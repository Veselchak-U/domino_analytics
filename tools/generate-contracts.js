import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import { validDateTime } from '../shared/time.js';
import { createHash } from 'node:crypto';
import { lessonCatalog, lessonDefinition } from '../shared/lessons.js';
import { digest } from '../shared/contract.js';

const schemaText=fs.readFileSync(new URL('../contracts/kozel-game.schema.json',import.meta.url),'utf8');
const ajv=new Ajv2020({strict:false,allErrors:true,code:{source:true,esm:true,formats:_`{"date-time": validDateTime}`},formats:{'date-time':validDateTime}});
let source=standaloneCode(ajv,ajv.compile(JSON.parse(schemaText)));
source=source.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g,'(s => Array.from(s).length)');
source=source.replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g,'jsonEqual');
if(source.includes('require('))throw new Error('Непереносимая зависимость в standalone-валидаторе');
const output=`// Generated by tools/generate-contracts.js; schema SHA-256 ${createHash('sha256').update(schemaText).digest('hex')}\nimport { validDateTime } from './time.js';\nimport { jsonEqual } from './equal.js';\n${source}\n`;
const target=new URL('../shared/game-schema.js',import.meta.url);
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==output)throw new Error('Обновите standalone-валидатор: node tools/generate-contracts.js');
}else fs.writeFileSync(target,output);

const lessons=lessonCatalog(),hash=await digest(lessons.map(l=>lessonDefinition(l.id)));
const manifest=`// Generated from versioned lesson definitions.\nexport const lessonManifest = ${JSON.stringify({hash,ids:lessons.map(l=>l.id),lessons},null,2)};\n`;
const manifestPath=new URL('../shared/lesson-manifest.js',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(manifestPath,'utf8')!==manifest)throw new Error('Обновите manifest уроков: npm run generate:contracts');}
else fs.writeFileSync(manifestPath,manifest);
